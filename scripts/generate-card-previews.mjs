// Scans docs folders for card-preview.tsx files and regenerates the lazy preview map.
// Run: node scripts/generate-card-previews.mjs
import { existsSync, readdirSync, writeFileSync } from "node:fs"
import { execFileSync } from "node:child_process"
import { join } from "node:path"

const DOCS = "app/[locale]/(docs)/docs"
const SECTIONS = ["components", "effects", "hooks"]

const entries = []
for (const section of SECTIONS) {
  const dir = join(DOCS, section)
  if (!existsSync(dir)) continue
  for (const slug of readdirSync(dir).sort()) {
    if (existsSync(join(dir, slug, "card-preview.tsx"))) {
      entries.push({ section, slug })
    }
  }
}

const header = "// GENERATED by scripts/generate-card-previews.mjs — do not edit by hand\n"

const generated = `"use client"

${header}
import dynamic from "next/dynamic"
import type { ComponentType } from "react"

export const PREVIEW_COMPONENTS: Record<string, ComponentType> = {
${entries
  .map(
    ({ section, slug }) =>
      `  "${slug}": dynamic(\n    () => import("@/${DOCS}/${section}/${slug}/card-preview"),\n    { ssr: false },\n  ),`,
  )
  .join("\n")}
}
`

const map = `${header}
import type { ComponentType } from "react"
import { LazyCardPreview } from "@/components/docs/lazy-card-preview"

const SLUGS = [
${entries.map(({ slug }) => `  "${slug}",`).join("\n")}
]

/** slug -> card preview for the catalog pages (mounted lazily on the client) */
export const CARD_PREVIEWS: Record<string, ComponentType> = Object.fromEntries(
  SLUGS.map((slug) => [slug, () => <LazyCardPreview slug={slug} />]),
)
`

writeFileSync("components/docs/card-previews.generated.tsx", generated)
writeFileSync("components/docs/card-previews.tsx", map)
// Keep the generated files in biome format so the lint stays clean
execFileSync(
  "pnpm",
  [
    "exec",
    "biome",
    "format",
    "--write",
    "components/docs/card-previews.generated.tsx",
    "components/docs/card-previews.tsx",
  ],
  { stdio: "ignore" },
)
console.log(`card previews: ${entries.length}`)
